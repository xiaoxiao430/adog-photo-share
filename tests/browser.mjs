// Run against a fresh, isolated QA instance; never point this at production.
import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
const require=createRequire(process.env.AIDOG_PHOTOS_QA_PACKAGE_JSON || new URL('../package.json', import.meta.url));
const {chromium}=require('playwright');
const root=path.resolve(import.meta.dirname,'..'), origin='http://127.0.0.1:18989', base=origin+'/aidog-photos';
const browser=await chromium.launch({headless:true,executablePath:process.env.PHOTO_SAVE_BROWSER || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
let checks=0; const errors=[];
function check(value){assert(value);checks++;}
const adminContext=await browser.newContext({viewport:{width:1360,height:1000}}), admin=await adminContext.newPage();
const watch=page=>{page.on('pageerror',e=>errors.push(e.message));}; watch(admin);
const stats=async()=>{const r=await adminContext.request.get(base+'/api/admin/photos');return r.json();};
const waitStat=async(key,count)=>admin.waitForFunction(([key,count])=>document.getElementById('stat-'+key)?.textContent===String(count),[key,count]);
try {
  const empty=await browser.newPage({viewport:{width:390,height:844}});watch(empty);
  await empty.goto(base+'/');await empty.locator('#empty-state').waitFor({state:'visible'});
  check(await empty.locator('.platform-card').count()===3);await empty.close();
  await admin.goto(base+'/admin');await admin.locator('#login-section').waitFor({state:'visible'});
  await admin.locator('#password').fill(await fs.readFile(root+'/.local/qa/qa-password','utf8'));
  await admin.locator('#login-button').click();await admin.locator('#admin-main').waitFor({state:'visible'});
  await admin.locator('#photo-files').setInputFiles(Array.from({length:9},(_,i)=>root+'/.local/qa/photos/qa-'+(i+1)+'.png'));
  await waitStat('all',9);check((await stats()).stats.available===9);
  await admin.locator('#photo-files').setInputFiles(root+'/.local/qa/photos/qa-1.png');
  await admin.waitForFunction(()=>document.getElementById('upload-status')?.textContent.includes('重复跳过'));
  check((await stats()).stats.all===9);
  const aContext=await browser.newContext({viewport:{width:390,height:844}});
  await aContext.addInitScript(()=>{
    window.shareMode='cancel';window.shareCalls=0;
    Object.defineProperty(navigator,'canShare',{value:()=>true});
    Object.defineProperty(navigator,'share',{value:({files})=>{window.shareCalls++; if(files.length!==3)throw Error('expected 3');return window.shareMode==='cancel'?Promise.reject(new DOMException('Cancelled','AbortError')):Promise.resolve();}});
  });
  const a=await aContext.newPage();watch(a);await a.goto(base+'/');await a.locator('#save-button').waitFor({state:'visible'});
  await a.waitForFunction(()=>!document.getElementById('save-button').disabled);
  await a.evaluate(()=>document.fonts.ready);check(await a.evaluate(()=>document.fonts.check('14px Yahei')));
  const idsA=await a.locator('.photo-tile img').evaluateAll(imgs=>imgs.map(img=>img.getAttribute('src')));
  check(idsA.length===3);check((await stats()).stats.used===0);
  const bottom=await a.locator('.platform-grid').boundingBox();check(bottom.y+bottom.height<844);
  await a.screenshot({path:root+'/output/顾客页-手机检查.png',fullPage:true});
  await a.locator('#save-button').click();await a.locator('#guest-message').filter({hasText:'已取消'}).waitFor();
  check((await stats()).stats.used===0);
  await a.evaluate(()=>window.shareMode='success');await a.locator('#save-button').click();
  await a.waitForFunction(()=>document.getElementById('batch-state').textContent==='已领取');
  const afterA=await stats();check(afterA.stats.used===3);check(new Set(afterA.photos.filter(x=>x.status==='used').map(x=>x.usedAt)).size===1);
  await a.locator('#save-button').click();await a.waitForFunction(()=>!document.getElementById('save-button').disabled);
  check((await stats()).stats.used===3);
  const bContext=await browser.newContext({viewport:{width:390,height:844}});
  await bContext.addInitScript(()=>Object.defineProperty(navigator,'canShare',{value:()=>false}));
  const b=await bContext.newPage();watch(b);
  await b.goto(base+'/');await b.waitForFunction(()=>!document.getElementById('save-button').disabled);
  const idsB=await b.locator('.photo-tile img').evaluateAll(imgs=>imgs.map(img=>img.getAttribute('src')));check(!idsA.some(id=>idsB.includes(id)));
  await b.locator('#save-button').click();await b.locator('#save-dialog').waitFor({state:'visible'});
  check(await b.locator('.download-one').count()===3);await b.locator('#manual-confirm').click();
  await b.waitForFunction(()=>document.getElementById('batch-state').textContent==='已领取');check((await stats()).stats.used===6);
  await a.locator('#next-button').click();await a.waitForFunction(()=>!document.getElementById('save-button').disabled);
  check((await a.locator('.photo-tile img').evaluateAll(imgs=>imgs.map(x=>x.getAttribute('src')))).every(id=>!idsA.includes(id)&&!idsB.includes(id)));
  await a.route('**/api/batch/commit',route=>route.abort());
  await a.locator('#save-button').click();await a.waitForFunction(()=>localStorage.getItem('aidog-photos-pending-v1')!==null);
  await a.waitForFunction(()=>document.getElementById('save-button').textContent.includes('重试同步'));
  check((await stats()).stats.used===6);
  await a.unroute('**/api/batch/commit');await a.locator('#save-button').click();
  await a.waitForFunction(()=>document.getElementById('batch-state').textContent==='已领取');check((await stats()).stats.used===9);
  await admin.locator('#refresh-photos').click();await waitStat('used',9);
  await admin.locator('[data-filter="used"]').click();await admin.waitForFunction(()=>document.querySelectorAll('.admin-photo-card').length===9);
  check((await admin.locator('.photo-card-time').allTextContents()).every(x=>x.includes('使用：')));
  await admin.evaluate(()=>document.fonts.ready);await admin.screenshot({path:root+'/output/后台-桌面检查.png',fullPage:true});
  await admin.locator('#settings-open').click();await admin.locator('#settings-dialog').waitFor({state:'visible'});
  await admin.locator('#platform-douyin').fill('https://www.douyin.com/');await admin.locator('#settings-save').click();
  await admin.locator('#settings-dialog').waitFor({state:'hidden'});check((await stats()).platforms.find(x=>x.id==='douyin').url==='https://www.douyin.com/');
  check(errors.length===0);
  await fs.writeFile(root+'/output/browser-check.json',JSON.stringify({ok:true,checks,pageErrors:errors,phoneAlbumSaveVerified:false,systemShareMocked:true,productionTouched:false},null,2)+'\n');
  console.log(JSON.stringify({ok:true,checks,pageErrors:errors.length,productionTouched:false}));
} finally {await browser.close();}
